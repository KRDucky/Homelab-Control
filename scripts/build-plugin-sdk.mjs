// Build with the already pinned TypeScript compiler; users of the plugin SDK need only Node >=22.
import ts from '../frontend/app/node_modules/typescript/lib/typescript.js';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (path) => readFileSync(resolve(root, path), 'utf8');
const check = process.argv.includes('--check');
function output(path, contents) {
  if (check) {
    if (read(path) !== contents) throw new Error(`Generated plugin artifact drift: ${path}. Run node scripts/build-plugin-sdk.mjs.`);
  } else writeFileSync(resolve(root, path), contents);
}

// Must match CONTRIBUTION_IDS in frontend/app/src/plugin.ts (the single source of parser rules).
const contributionIds = ['overview.sample-card'];

// The app source is frontend/app/src/plugin.ts. The SDK runtime is that source minus the
// browser-only persistence tail (localStorage/window), the same way build-theme-sdk.mjs shares theme.ts.
let source = read('frontend/app/src/plugin.ts');
const marker = '// --- Browser-only persistence below (not part of the SDK runtime). ---';
const cut = source.indexOf(marker);
if (cut < 0) throw new Error(`Marker not found in plugin.ts: ${marker}`);
source = source.slice(0, cut);
const runtime = ts.transpileModule(source, {
  compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, removeComments: false },
}).outputText;
output('sdk/plugin/runtime.mjs', '// Generated by scripts/build-plugin-sdk.mjs. Do not edit.\n' + runtime);

const schema = {
  $schema: 'https://json-schema.org/draft/2020-12/schema',
  $id: 'urn:homelab-control:schema:plugin:v1',
  title: 'HCIS read-only plugin manifest v1',
  type: 'object',
  additionalProperties: false,
  required: ['schemaVersion', 'id', 'name', 'version', 'license', 'contributions'],
  properties: {
    schemaVersion: { const: 1 },
    id: { type: 'string', maxLength: 100, pattern: '^[a-z0-9]+(\\.[a-z0-9-]+){1,4}$' },
    name: {
      type: 'string',
      minLength: 1,
      maxLength: 80,
      pattern: '^[^<>\\u0000-\\u001f\\u007f\\u202a-\\u202e\\u2066-\\u2069]*$',
    },
    version: { type: 'string', pattern: '^(0|[1-9][0-9]*)\\.(0|[1-9][0-9]*)\\.(0|[1-9][0-9]*)$' },
    license: { type: 'string', pattern: '^[a-zA-Z0-9.+-]{2,40}$' },
    contributions: {
      type: 'array',
      minItems: 1,
      uniqueItems: true,
      items: { enum: contributionIds },
    },
  },
};
output('schemas/plugin/v1.json', JSON.stringify(schema, null, 2) + '\n');
console.log(check ? 'Plugin SDK artifacts match the application.' : 'Generated plugin SDK runtime and schema.');
