// Build with the already pinned TypeScript compiler; users of the TDK need only Node >=22.
import ts from '../frontend/app/node_modules/typescript/lib/typescript.js';
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (path) => readFileSync(resolve(root, path), 'utf8');
const check = process.argv.includes('--check');
function output(path, contents) {
  if (check) { if (read(path) !== contents) throw new Error(`Generated theme artifact drift: ${path}. Run node scripts/build-theme-sdk.mjs.`); }
  else writeFileSync(resolve(root, path), contents);
}
const tokens = JSON.parse(read('docs/ui/hcis/tokens/tokens.json')).color.tokens;
const byName = Object.fromEntries(tokens.map((t) => [t.name, t.value]));
function color(name, base) {
  const raw = byName[name], value = typeof raw === 'string' ? raw : raw[base];
  return value.startsWith('{') ? color(value.slice(1, -1), base) : value;
}
const bases = ['midnight', 'daybreak', 'graphite', 'oled'];
const palettes = Object.fromEntries(bases.map((base) => [base, Object.fromEntries(tokens.filter((t) => t.name.startsWith('hc-color-')).map((t) => [t.name.slice(9), color(t.name, base)]))]));
output('frontend/app/src/theme-palettes.json', JSON.stringify(palettes, null, 2) + '\n');
let source = read('frontend/app/src/theme.ts').replace("import palettes from './theme-palettes.json';", `const palettes = ${JSON.stringify(palettes)};`);
source = source.slice(0, source.indexOf('export function applyTheme')) + source.slice(source.indexOf('export function newTheme'));
const runtime = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, removeComments: false } }).outputText;
output('sdk/theme/runtime.mjs', '// Generated by scripts/build-theme-sdk.mjs. Do not edit.\n' + runtime);
const aliases = ['ink', 'panel', 'panel-raised', 'rule', 'text', 'muted', 'signal', 'signal-ink', 'ok', 'warn', 'crit', 'focus'];
const keys = Object.keys(palettes.midnight).filter((k) => !aliases.includes(k));
const schema = {
  $schema: 'https://json-schema.org/draft/2020-12/schema', $id: 'urn:homelab-control:schema:theme:v1', title: 'HCIS colour theme v1', type: 'object', additionalProperties: false,
  required: ['schemaVersion', 'id', 'name', 'version', 'license', 'base', 'colors'],
  properties: {
    schemaVersion: { const: 1 }, id: { type: 'string', maxLength: 100, pattern: '^[a-z0-9]+(\\.[a-z0-9-]+){1,4}$' },
    name: { type: 'string', minLength: 1, maxLength: 80, pattern: '^[^<>\\u0000-\\u001f\\u007f\\u202a-\\u202e\\u2066-\\u2069]*$' },
    version: { type: 'string', pattern: '^(0|[1-9][0-9]*)\\.(0|[1-9][0-9]*)\\.(0|[1-9][0-9]*)$' },
    license: { type: 'string', pattern: '^[a-zA-Z0-9.+-]{2,40}$' }, base: { enum: bases },
    colors: { type: 'object', additionalProperties: false, properties: Object.fromEntries(keys.map((k) => [k, { type: 'string', pattern: '^#[0-9a-fA-F]{6}([0-9a-fA-F]{2})?$' }])) },
  },
};
output('schemas/theme/v1.json', JSON.stringify(schema, null, 2) + '\n');
for (const base of bases) output(`sdk/theme/examples/${base}.hltheme`, JSON.stringify({ schemaVersion: 1, id: `example.${base}`, name: `${base[0].toUpperCase() + base.slice(1)} starter`, version: '1.0.0', license: 'MIT', base, colors: {} }, null, 2) + '\n');
console.log(check ? 'Theme SDK artifacts match the application.' : 'Generated theme SDK, schema, starter themes and palettes.');
